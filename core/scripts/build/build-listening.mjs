import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../../', import.meta.url));
const source = path.join(root, 'core/scripts/build/listening');
const extension = path.join(root, 'extensions/基础题型/听力理解');
const read = file => fs.readFileSync(file, 'utf8').replaceAll('\r\n', '\n');
const banner = '/* Generated by node core/scripts/build/build-listening.mjs. Edit core/scripts/build/listening/ sources. */\n';
const shared = read(path.join(source, 'audio-reference.js'));
const player = read(path.join(source, 'audio-player.js'));
const encoderRoot = path.join(root, 'core/node_modules/@breezystack/lamejs');
const encoder = '/*! @breezystack/lamejs 1.2.7, LGPL-3.0; see LICENSE.lamejs.txt and THIRD_PARTY.md. */\n' + read(path.join(encoderRoot, 'dist/lamejs.iife.js'));
for (const [name, parts] of [
  ['practice.js', [shared, player, read(path.join(source, 'listen-page.js'))]],
  ['editor.js', [shared, player, encoder, read(path.join(source, 'audio-import.js')), read(path.join(source, 'listen-editor.js'))]],
  ['rules.js', [shared, read(path.join(source, 'rules.js'))]],
]) fs.writeFileSync(path.join(extension, name), banner + parts.join('\n\n') + '\n');
const base = read(path.join(root, 'extensions/基础题型/单选题/practice.css')).replaceAll('single-choice-card', 'listen-card');
fs.writeFileSync(path.join(extension, 'practice.css'), banner + [base, read(path.join(source, 'audio-player.css')), read(path.join(source, 'listen-page.css'))].join('\n\n'));
fs.copyFileSync(path.join(encoderRoot, 'LICENSE'), path.join(extension, 'LICENSE.lamejs.txt'));
for (const name of ['practice.js', 'editor.js', 'rules.js', 'practice.css']) console.log(`${name}: ${fs.statSync(path.join(extension, name)).size} bytes`);
